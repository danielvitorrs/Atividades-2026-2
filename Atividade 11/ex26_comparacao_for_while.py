# Exercicio 26: a mesma contagem usando for e while.
print("Com for:")
for numero in range(1, 21):
    print(numero)

print("\nCom while:")
numero = 1
while numero <= 20:
    print(numero)
    numero += 1

# O for percorre diretamente uma sequencia de valores. O while repete enquanto
# uma condicao for verdadeira e exige atualizar o contador manualmente.
